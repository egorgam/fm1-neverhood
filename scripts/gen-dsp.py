#!/usr/bin/env python3
"""Small interpolated sine table: no libm calls in the sample-rate oscillator."""
import argparse
import math
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument("--out", type=Path, required=True)
args = parser.parse_args()
values = [f"{math.sin(2 * math.pi * i / 1024):.9f}f" for i in range(1025)]
lines = ["/* Generated by scripts/gen-dsp.py. */", "static const float CLAY_SINE[1025] = {"]
lines += ["    " + ", ".join(values[i:i + 8]) + "," for i in range(0, len(values), 8)]
lines += ["};", ""]
args.out.parent.mkdir(parents=True, exist_ok=True)
args.out.write_text("\n".join(lines))
