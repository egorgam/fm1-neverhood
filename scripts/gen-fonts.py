#!/usr/bin/env python3
"""Bake the bundled hand-drawn faces into fm1-base's 4-bit alpha format."""
import argparse
import math
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
PAD, SCALE = 2, 4
parser = argparse.ArgumentParser()
parser.add_argument("--out", type=Path, required=True)
args = parser.parse_args()
lines = ["/* Generated by scripts/gen-fonts.py; see assets/fonts/README.md for licenses. */",
         "#pragma once", "#include <stdint.h>", f"#define FONT_PAD {PAD}"]

for role, filename, px, last in [("XS", "ChelseaMarket-Regular.ttf", 11, 126),
                                 ("S", "ChelseaMarket-Regular.ttf", 16, 126),
                                 ("M", "Kranky-Regular.ttf", 28, 95)]:
    font = ImageFont.truetype(str(ROOT / "assets/fonts" / filename), px * SCALE)
    boxes = [font.getbbox(chr(c)) for c in range(33, last + 1)]
    top = math.floor(min(b[1] for b in boxes) / SCALE)
    height = math.ceil(max(b[3] for b in boxes) / SCALE) - top
    advances, widths, offsets, data = [], [], [], []
    for code in range(32, last + 1):
        char = chr(code)
        advance = round(font.getlength(char) / SCALE)
        width = advance + PAD * 2
        mask = Image.new("L", (width * SCALE, height * SCALE))
        ImageDraw.Draw(mask).text((PAD * SCALE, -top * SCALE), char, font=font, fill=255)
        mask = mask.resize((width, height), Image.Resampling.LANCZOS)
        pixels = list(mask.getdata())
        advances.append(advance)
        widths.append(width)
        offsets.append(len(data))
        for y in range(height):
            row = [min(15, (v + 8) // 17) for v in pixels[y * width:(y + 1) * width]] + [0]
            data.extend((row[x] << 4) | row[x + 1] for x in range(0, width, 2))
    assert len(data) < 65536
    prefix = f"FONT_{role}"
    for suffix, ctype, values in [("ADV", "uint8_t", advances), ("BW", "uint8_t", widths),
                                   ("OFF", "uint16_t", offsets), ("DATA", "uint8_t", data)]:
        lines.append(f"static const {ctype} {prefix}_{suffix}[] = {{")
        lines.extend("    " + ",".join(map(str, values[i:i + 24])) + "," for i in range(0, len(values), 24))
        lines.append("};")
    lines.append(f"static const felucca_font_t {prefix} = {{ {height}, {PAD}, 32, {last}, "
                 f"{prefix}_ADV, {prefix}_BW, {prefix}_OFF, {prefix}_DATA }};")
    print(f"clay font {role}: {filename}, {px}px, height {height}, {len(data)} B")

# The platform's splash, dialogs and calibration use these roles too.
lines += ["#define FONT_T FONT_XS", "#define FONT_B FONT_S", "#define FONT_L FONT_M", ""]
args.out.parent.mkdir(parents=True, exist_ok=True)
args.out.write_text("\n".join(lines))
